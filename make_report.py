ns_a = "http://schemas.openxmlformats.org/drawingml/2006/main"
ns_rid = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
with ZipFile(output, "r") as zin:
    rel_root = ET.fromstring(zin.read(rels_name))
    body_root = ET.fromstring(zin.read(document_name))
    used_ids = set()
    for node in body_root.iter():
        for attr in (f"{{{ns_rid}}}embed", f"{{{ns_rid}}}id"):
            if node.get(attr):
                used_ids.add(node.get(attr))
    unused_targets = set()
    for rel in list(rel_root):
        if rel.get("Type", "").endswith("/image") and rel.get("Id") not in used_ids:
            unused_targets.add(posixpath.normpath(posixpath.join("word", rel.get("Target"))))
            rel_root.remove(rel)
    files = [(item, zin.read(item.filename)) for item in zin.infolist() if item.filename not in unused_targets]
with ZipFile(output.with_suffix(".clean.docx"), "w", ZIP_DEFLATED) as zout:
    for item, content in files:
        if item.filename == rels_name:
            content = ET.tostring(rel_root, encoding="utf-8", xml_declaration=True)
        zout.writestr(item, content)
output.with_suffix(".clean.docx").replace(output)
print(output)
